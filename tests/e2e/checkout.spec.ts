test('pedido pendente sobrevive a refresh, recusa preserva carrinho e confirmação baixa só o comprado', async ({ page }) => {
  await login(page)
  await connect(page)
  await scenario(page, 'payment-pending')
  await confirm(page)
  await expect(page.getByRole('heading', { name: 'Pagamento pendente', exact: true })).toBeVisible()
  const declinedId = new URL(page.url()).pathname.split('/').at(-1)!
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Pagamento pendente', exact: true })).toBeVisible()
  await expect(page.getByTestId('order-receipt')).toHaveCount(0)
  await scenario(page, 'server-error')
  await page.getByRole('button', { name: 'Verificar pedido', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Não foi possível consultar o pedido' })).toBeVisible()
  await scenario(page, 'default')
  await page.getByRole('button', { name: 'Verificar pedido', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pagamento pendente', exact: true })).toBeVisible()
  await scenario(page, 'payment-pending')
  await api(page, `/__mock/orders/${declinedId}/settle`, 'POST', { status: 'declined' })
  await expect(page.getByRole('heading', { name: 'Pagamento recusado', exact: true })).toBeVisible()
  expect((await api<Cart>(page, '/cart')).data.items[0]?.quantity).toBe(1)
  await page.goto('/checkout')
  await confirm(page)
  await expect(page.getByRole('heading', { name: 'Pagamento pendente', exact: true })).toBeVisible()
  const confirmedId = new URL(page.url()).pathname.split('/').at(-1)!
  expect(confirmedId).not.toBe(declinedId)
  await api(page, '/cart/items', 'POST', { nftId: 'nft-002', editionId: 'nft-002-ed-10', quantity: 1 })
  await api(page, `/__mock/orders/${confirmedId}/settle`, 'POST', { status: 'confirmed' })
  await expect(page.getByRole('heading', { name: 'Compra confirmada', exact: true })).toBeVisible()
  expect((await api<Cart>(page, '/cart')).data.items[0]?.quantity).toBe(1)
})

test('timeout depois do commit e refresh recuperam exatamente a mesma intenção sem duplicar pedido', async ({ page }) => {
  test.setTimeout(45000)
  await login(page)
  await connect(page)
  await scenario(page, 'order-timeout')
  const posts: { key: string | undefined; body: string | null }[] = []
  page.on('request', (request) => { if (isOrderPost(request)) posts.push({ key: request.headers()['idempotency-key'], body: request.postData() }) })
  await confirm(page)
  await expect(page.getByRole('heading', { name: 'Verificando resultado da tentativa', exact: true })).toBeVisible({ timeout: 15000 })
  expect((await api<{ items: Order[] }>(page, '/orders')).data.items).toHaveLength(2)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Verificando resultado da tentativa', exact: true })).toBeVisible()
  expect(posts).toHaveLength(1)
  await page.getByRole('button', { name: 'Recuperar mesma tentativa' }).click()
  await expect(page.getByRole('heading', { name: 'Compra confirmada', exact: true })).toBeVisible()
  expect(posts).toHaveLength(2)
  expect(posts[1]).toEqual(posts[0])
  expect((await api<{ items: Order[] }>(page, '/orders')).data.items).toHaveLength(2)
})

test('Socket.IO bloqueia preço, estoque e cupom obsoletos; falhas de consulta recuperam', async ({ page }) => {
  await login(page)
  await connect(page)
  await review(page)
  await api(page, '/__mock/nfts/nft-002', 'PATCH', { editionId: 'nft-002-ed-10', priceEth: '0.100000000000000001' })
  await expect(reviewDialog(page).getByRole('button', { name: 'Confirmar compra simulada' })).toBeDisabled()
  await expect(reviewDialog(page).getByRole('alert')).toContainText('A cotação mudou')
  await reviewDialog(page).getByRole('button', { name: 'Voltar à edição' }).click()
  await expect(page.locator('.checkout-summary').getByTestId('purchase-total')).toHaveText('0.116000000000000001 ETH')
  await api(page, '/__mock/nfts/nft-002', 'PATCH', { editionId: 'nft-002-ed-10', availableQuantity: 0 })
  await expect(reviewButton(page)).toBeDisabled()
  await expect(page.getByRole('alert').filter({ hasText: 'Revise os itens' })).toBeVisible()
  expect((await api<{ items: Order[] }>(page, '/orders')).data.items).toHaveLength(1)
  await api(page, '/__mock/nfts/nft-002', 'PATCH', { editionId: 'nft-002-ed-10', availableQuantity: 8 })
  await expect(reviewButton(page)).toBeEnabled()
  await api(page, '/cart/coupon', 'PUT', { code: 'WELCOME10' })
  await page.reload()
  await review(page)
  await scenario(page, 'coupon-expired')
  await reviewDialog(page).getByRole('button', { name: 'Confirmar compra simulada' }).click()
  await expect(reviewDialog(page)).not.toBeVisible()
  await expect(page.getByRole('alert').filter({ hasText: /cupom.*expir/i }).first()).toBeVisible()
  await expect(reviewButton(page)).toBeDisabled()
  await scenario(page, 'default')
  await api(page, '/cart/coupon', 'DELETE')
  await scenario(page, 'server-error')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Não foi possível verificar a sessão' })).toBeVisible()
  await scenario(page, 'slow')
  await page.getByRole('button', { name: 'Verificar novamente', exact: true }).click()
  await expect(page.getByTestId('checkout-skeleton')).toBeVisible()
  await expect(reviewButton(page)).toBeEnabled()
})

