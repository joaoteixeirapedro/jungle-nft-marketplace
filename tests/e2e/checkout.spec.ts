import { expect, test, type Page, type Request } from '@playwright/test'
import type { Cart, Order, Receipt } from '../../src/types/marketplace.ts'

async function api<T>(page: Page, path: string, method = 'GET', body?: object) {
  return page.evaluate(async ({ path, method, body }) => {
    const token = sessionStorage.getItem('jungle-marketplace.session')
    const response = await fetch(`/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}), 'X-Guest-Id': sessionStorage.getItem('jungle-marketplace.guest') ?? 'checkout-test' }, body: body ? JSON.stringify(body) : undefined })
    return { status: response.status, data: response.status === 204 ? null as T : await response.json() as T }
  }, { path, method, body })
}
const scenario = (page: Page, name: string) => api(page, '/__mock/scenario', 'PUT', { scenario: name })
const isOrderPost = (request: Request) => request.method() === 'POST' && new URL(request.url()).pathname === '/api/orders'
const reviewDialog = (page: Page) => page.getByRole('dialog', { name: 'Revisar compra simulada' })
const reviewButton = (page: Page) => page.getByRole('button', { name: 'Revisar compra', exact: true }).filter({ visible: true })
async function signIn(page: Page, account = 'alice') {
  await page.getByLabel('E-mail', { exact: true }).fill(`${account}@example.test`)
  await page.getByLabel('Senha', { exact: true }).fill('Demo#2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
}
async function login(page: Page, account = 'alice') {
  await page.goto('/login?redirect=%2Fcheckout')
  await signIn(page, account)
  await expect(page.getByRole('heading', { name: 'Pagamento com carteira', exact: true })).toBeVisible()
}
async function connect(page: Page) {
  await page.getByRole('button', { name: 'Conectar carteira simulada', exact: true }).click()
  await expect(page.locator('.connection-status')).toHaveText('Carteira conectada na simulação')
  await expect(reviewButton(page)).toBeEnabled()
}
async function review(page: Page) {
  await expect(reviewButton(page)).toBeEnabled()
  await reviewButton(page).click()
  await expect(reviewDialog(page)).toBeVisible()
  await expect(reviewDialog(page).getByRole('button', { name: 'Voltar à edição' })).toBeFocused()
}
async function confirm(page: Page) { await review(page); await reviewDialog(page).getByRole('button', { name: 'Confirmar compra simulada' }).click() }
async function logout(page: Page) {
  await page.goto('/profile')
  await page.locator('.account-page').getByRole('button', { name: 'Sair da conta', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
}
