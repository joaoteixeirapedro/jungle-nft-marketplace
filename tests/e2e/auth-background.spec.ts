import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const login = (page: Page) => page.getByRole('dialog', { name: 'Entrar', exact: true })
const entry = (page: Page, mobile: boolean) => page.locator(mobile ? '.mobile-navigation' : '.header-actions').getByRole('link', { name: 'Entrar', exact: true })

test.beforeEach(async ({ page }) => {
  await page.goto('/marketplace')
  await expect(page.getByTestId('nft-card')).toHaveCount(9)
  await page.evaluate(() => fetch('/api/__mock/reset', { method: 'POST' }))
})

test('login conserva catálogo, rolagem, cadastro e histórico do navegador', async ({ page, isMobile }) => {
  await page.goto('/marketplace?page=2')
  await expect(page.getByTestId('nft-card')).toHaveCount(9)
  const catalog = page.locator('.discovery-catalog')
  const cards = await catalog.getByTestId('nft-card').allTextContents()
  await catalog.evaluate((element) => element.setAttribute('data-preserved', 'catalog'))
  await entry(page, isMobile).click()
  await expect(login(page)).toBeVisible()
  await expect(catalog).toHaveAttribute('data-preserved', 'catalog')
  expect(await catalog.getByTestId('nft-card').allTextContents()).toEqual(cards)
  await expect(page.locator('.market-shell')).toHaveAttribute('inert', '')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  const register = login(page).getByRole('link', { name: 'Criar conta', exact: true })
  if (await register.isVisible()) await register.click()
  else await login(page).getByRole('link', { name: 'Crie uma conta', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Criar perfil de colecionador' })).toBeVisible()
  await expect(catalog).toHaveAttribute('data-preserved', 'catalog')
  await page.getByRole('button', { name: 'Voltar sem entrar' }).click()
  await expect(page).toHaveURL(/\/marketplace\?page=2$/)
  await expect(entry(page, isMobile)).toBeFocused()
  await page.evaluate(() => window.scrollTo(0, 550))
  const scroll = await page.evaluate(() => window.scrollY)
  if (!isMobile) await catalog.getByTestId('nft-card').first().hover()
  await catalog.getByTestId('nft-card').first().locator('.nft-favorite').click()
  const beforeClose = await page.evaluate(() => window.scrollY)
  await expect(login(page)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(login(page)).not.toBeVisible()
  expect(await page.evaluate(() => window.scrollY)).toBe(beforeClose)
  expect(scroll).toBeGreaterThan(0)
  await entry(page, isMobile).click()
  await expect(login(page)).toBeVisible()
  await page.goBack()
  await expect(login(page)).not.toBeVisible()
  await page.goForward()
  await expect(login(page)).toBeVisible()
  await page.reload()
  await expect(login(page)).toBeVisible()
  await expect(catalog.getByTestId('nft-card')).toHaveCount(9)
  await page.getByRole('button', { name: 'Voltar sem entrar' }).click()
  await expect(page).toHaveURL(/\/marketplace\?page=2$/)
  await page.reload()
  await expect(catalog.getByTestId('nft-card')).toHaveCount(9)
  await expect(page.locator('dialog[open]')).toHaveCount(0)
})

test('favorito mantém NFT, edição e quantidade ao fechar e autenticar', async ({ page, isMobile }) => {
  await page.goto('/nfts/nft-001')
  const edition = page.locator('input[value="nft-001-ed-50"]')
  const quantity = page.locator('#nft-quantity')
  await edition.check()
  await quantity.fill('3')
  const favorite = page.locator(isMobile ? '.favorite-mobile button' : '.favorite-detail button')
  await favorite.click()
  await expect(login(page)).toBeVisible()
  await expect(edition).toBeChecked()
  await expect(quantity).toHaveValue('3')
  await page.getByRole('button', { name: 'Voltar sem entrar' }).click()
  await expect(page).toHaveURL(/\/nfts\/nft-001$/)
  await expect(favorite).toBeFocused()
  await expect(edition).toBeChecked()
  await expect(quantity).toHaveValue('3')
  await favorite.click()
  await page.getByLabel('E-mail', { exact: true }).fill('alice@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo#2026')
  await login(page).getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(login(page)).not.toBeVisible()
  await expect(page).toHaveURL(/\/nfts\/nft-001$/)
  await expect(edition).toBeChecked()
  await expect(quantity).toHaveValue('3')
})

test('atalho de rota protegida abre login sobre a página de origem', async ({ page, isMobile }) => {
  await page.goto('/marketplace?page=2')
  await page.locator('.discovery-catalog').evaluate((element) => element.setAttribute('data-preserved', 'catalog'))
  const link = isMobile ? page.locator('.mobile-navigation').getByRole('link', { name: 'Favoritos', exact: true }) : page.locator('.site-footer').getByRole('link', { name: 'Meu perfil', exact: true })
  await link.click()
  await expect(login(page)).toBeVisible()
  await expect(page.locator('.discovery-catalog')).toBeVisible()
  await expect(page.locator('.discovery-catalog')).toHaveAttribute('data-preserved', 'catalog')
  expect(new URL(page.url()).searchParams.get('redirect')).toBe(isMobile ? '/favorites' : '/profile')
  await page.getByRole('button', { name: 'Voltar sem entrar' }).click()
  await expect(page).toHaveURL(/\/marketplace\?page=2$/)
})
