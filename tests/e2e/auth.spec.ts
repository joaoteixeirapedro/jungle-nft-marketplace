async function api<T = Record<string, unknown>>(page: Page, path: string, method = 'GET', body?: object, token?: string, headers: Record<string, string> = {}) {
  return page.evaluate(async ({ path, method, body, token, headers }) => {
    const active = token ?? sessionStorage.getItem('jungle-marketplace.session')
    const response = await fetch(`/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(active ? { Authorization: `Bearer ${active}` } : {}), ...headers }, body: body ? JSON.stringify(body) : undefined })
    const text = await response.text()
    return { status: response.status, data: text ? JSON.parse(text) as T : null }
  }, { path, method, body, token, headers })
}
async function scenario(page: Page, name: string) { expect((await api(page, '/__mock/scenario', 'PUT', { scenario: name })).status).toBe(200) }
const dialog = (page: Page) => page.getByRole('dialog', { name: 'Entrar', exact: true })
const submit = (page: Page) => dialog(page).getByRole('button', { name: 'Entrar', exact: true })
async function signIn(page: Page, user = 'alice') {
  await expect(dialog(page)).toBeVisible()
  await page.getByLabel('E-mail', { exact: true }).fill(`${user}@example.test`)
  await page.getByLabel('Senha', { exact: true }).fill('Demo#2026')
  await submit(page).click()
  await expect(dialog(page)).not.toBeVisible()
}
async function logout(page: Page) {
  const profileLink = page.getByRole('navigation', { name: 'Conta do colecionador' }).getByRole('link', { name: 'Meu perfil, Dados do perfil', exact: true })
  if (await profileLink.isVisible()) await profileLink.click()
  else await page.goto('/profile')
  await page.locator('.account-page').getByRole('button', { name: 'Sair da conta', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
}
async function createPendingOrder(page: Page) {
  const wallets = (await api<{ items: Wallet[] }>(page, '/wallets')).data!.items
  const wallet = wallets[0]!
  expect((await api(page, `/wallets/${wallet.id}/connection`, 'POST', { network: wallet.network })).status).toBe(200)
  const quote = (await api<Quote>(page, '/quotes', 'POST', { network: wallet.network, walletId: wallet.id })).data!
  const response = await api<Order>(page, '/orders', 'POST', { quoteId: quote.id, network: wallet.network, walletId: wallet.id, collector: { displayName: wallet.displayName, username: wallet.profileName, profileName: wallet.profileName, email: wallet.email } }, undefined, { 'Idempotency-Key': `auth-${wallet.id}` })
  expect(response.status).toBe(201)
  return response.data!
}
