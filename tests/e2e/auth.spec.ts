test('login trata credenciais, falhas e resposta inválida; refresh e logout revogam sessão', async ({ page }) => {
  await page.goto('/login?redirect=%2Fprofile')
  await page.getByLabel('E-mail', { exact: true }).fill('alice@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('incorreta')
  await submit(page).click()
  await expect(dialog(page).getByRole('alert')).toContainText('E-mail ou senha incorretos')
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('alice@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo#2026')
  await scenario(page, 'network-error')
  await submit(page).click()
  await expect(dialog(page).getByRole('alert')).toContainText('Não foi possível concluir a requisição')
  await scenario(page, 'malformed-session')
  await submit(page).click()
  await expect(dialog(page).getByRole('alert')).toContainText('A API retornou uma sessão inválida')
  expect(await page.evaluate(() => sessionStorage.getItem('jungle-marketplace.session'))).toBeNull()
  await scenario(page, 'slow')
  const cancelled = page.waitForRequest((r) => r.method() === 'POST' && new URL(r.url()).pathname === '/api/session')
  await submit(page).click()
  await cancelled
  await dialog(page).press('Escape')
  await expect(page).toHaveURL(/\/marketplace$/)
  await page.waitForTimeout(900)
  expect(await page.evaluate(() => sessionStorage.getItem('jungle-marketplace.session'))).toBeNull()
  await scenario(page, 'default')
  await page.goto('/login?redirect=%2Fprofile')
  await page.getByLabel('E-mail', { exact: true }).fill('alice@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo#2026')
  await submit(page).click()
  await expect(page.getByTestId('account-identity')).toHaveText('alice')
  const token = await page.evaluate(() => sessionStorage.getItem('jungle-marketplace.session')!)
  const verified = page.waitForResponse((r) => r.request().method() === 'GET' && new URL(r.url()).pathname === '/api/session')
  await page.reload()
  expect((await verified).fromServiceWorker()).toBe(true)
  await expect(page.getByTestId('account-identity')).toHaveText('alice')
  const revoked = page.waitForResponse((r) => r.request().method() === 'DELETE' && new URL(r.url()).pathname === '/api/session')
  await logout(page)
  expect((await revoked).status()).toBe(204)
  expect((await api(page, '/session', 'GET', undefined, token)).status).toBe(401)
})

test('rotas privadas preservam destino, bloqueiam redirecionamento externo e distinguem 403', async ({ page }) => {
  test.setTimeout(45_000)
  const paths = ['/profile?tab=wallets', '/wallets', '/favorites', '/orders', '/orders/order-demo-alice', '/checkout?network=ethereum&quoteId=context-only#review']
  const privateReads: string[] = []
  // Visitor cart reads now power the public header; authenticated cart reads remain private.
  page.on('request', (r) => { if (r.method() === 'GET' && (/\/api\/(profile|wallets|favorites|orders)/.test(r.url()) || (/\/api\/cart/.test(r.url()) && r.headers().authorization))) privateReads.push(r.url()) })
  for (const path of paths) {
    await page.goto(path)
    await expect(dialog(page)).toBeVisible()
    expect(new URL(page.url()).searchParams.get('redirect')).toBe(path)
  }
  expect(privateReads).toEqual([])
  await signIn(page)
  await expect(page).toHaveURL(/\/checkout\?network=ethereum&quoteId=context-only#review$/)
  await expect(page.getByRole('heading', { name: 'Pagamento com carteira', exact: true })).toBeVisible()
  await logout(page)
  await page.goto('/login?redirect=https%3A%2F%2Fevil.example%2F')
  await signIn(page)
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/profile')
  await logout(page)
  await page.goto('/orders/order-demo-alice')
  await signIn(page, 'bruno')
  await expect(page.getByRole('heading', { name: 'Acesso não permitido' })).toBeVisible()
  await expect(page.getByTestId('account-identity')).toHaveText('bruno')
  expect(await page.evaluate(() => sessionStorage.getItem('jungle-marketplace.session'))).toBeTruthy()
})

