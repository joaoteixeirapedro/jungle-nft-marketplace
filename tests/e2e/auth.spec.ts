test('resposta privada atrasada e eventos Socket.IO não atravessam a troca de conta', async ({ page }) => {
  test.setTimeout(45_000)
  await page.goto('/login?redirect=%2Ffavorites')
  await signIn(page)
  await expect(page.getByTestId('nft-card')).toHaveCount(2)
  await scenario(page, 'payment-pending')
  const aliceOrder = await createPendingOrder(page)
  await scenario(page, 'slow')
  const oldRequest = page.waitForRequest((r) => r.method() === 'DELETE' && r.url().endsWith('/favorites/nft-001'))
  await page.locator('[data-nft-id="nft-001"] .nft-favorite').click()
  await oldRequest
  await scenario(page, 'default')
  await logout(page)
  await page.goto('/login?redirect=%2Ffavorites')
  await signIn(page, 'bruno')
  await expect(page.getByTestId('nft-card')).toHaveCount(1)
  await page.waitForTimeout(900)
  await expect(page.getByTestId('nft-card')).toHaveAttribute('data-nft-id', 'nft-002')
  await page.getByRole('navigation', { name: 'Conta do colecionador' }).getByRole('link', { name: 'Pedidos', exact: true }).click()
  await expect(page.getByTestId('account-summary')).toContainText('0 pedidos')
  let orderReads = 0
  page.on('request', (r) => { if (r.method() === 'GET' && new URL(r.url()).pathname === '/api/orders') orderReads++ })
  await api(page, `/__mock/orders/${aliceOrder.id}/settle`, 'POST', { status: 'confirmed' })
  await page.waitForTimeout(200)
  expect(orderReads).toBe(0)
  await scenario(page, 'payment-pending')
  await createPendingOrder(page)
  // The raw test setup does not touch Query: only Socket.IO can refresh this UI.
  await expect(page.getByTestId('account-summary')).toContainText('1 pedidos')
  expect(orderReads).toBeGreaterThan(0)
})
