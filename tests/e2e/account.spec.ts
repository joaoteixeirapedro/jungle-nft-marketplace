async function api<T = Record<string, unknown>>(page: Page, path: string, method = 'GET', body?: object, token?: string) {
  return page.evaluate(async ({ path, method, body, token }) => {
    const active = token ?? sessionStorage.getItem('jungle-marketplace.session')
    const response = await fetch(`/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(active ? { Authorization: `Bearer ${active}` } : {}) }, body: body ? JSON.stringify(body) : undefined })
    return { status: response.status, data: response.status === 204 ? null as T : await response.json() as T }
  }, { path, method, body, token })
}
const scenario = (page: Page, name: string) => api(page, '/__mock/scenario', 'PUT', { scenario: name })
const nav = (page: Page) => page.getByRole('navigation', { name: 'Conta do colecionador' })
const profileForm = (page: Page) => page.getByRole('form', { name: 'Dados do perfil', exact: true })
const passwordForm = (page: Page) => page.getByRole('form', { name: 'Alterar senha', exact: true })
const walletForm = (page: Page, role = 'principal') => page.getByRole('form', { name: `Dados da carteira ${role}`, exact: true })
const field = (page: Page, name: string) => profileForm(page).locator(`[name="${name}"]`)
async function login(page: Page, user = 'alice', password = 'Demo#2026', destination = '/profile') {
  await page.goto(`/login?redirect=${encodeURIComponent(destination)}`)
  await page.getByLabel('E-mail', { exact: true }).fill(`${user}@example.test`)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByTestId('account-identity')).toHaveText(user)
}
async function logout(page: Page) {
  await page.locator('.account-page').getByRole('button', { name: 'Sair da conta', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
}
