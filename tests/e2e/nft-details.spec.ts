import { expect, test, type Page } from '@playwright/test'
import type { NftDetail, SessionResponse } from '../../src/types/marketplace.ts'

async function api<T>(page: Page, path: string, method = 'GET', body?: object) {
  return page.evaluate(async ({ path, method, body }) => {
    const token = sessionStorage.getItem('jungle-marketplace.session')
    const response = await fetch(`/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body ? JSON.stringify(body) : undefined })
    return { status: response.status, data: await response.json() as T }
  }, { path, method, body })
}
async function scenario(page: Page, name: string) { await api(page, '/__mock/scenario', 'PUT', { scenario: name }) }
async function login(page: Page, email: string) {
  await expect(page.locator('#nft-title')).toBeVisible()
  const response = await api<SessionResponse>(page, '/session', 'POST', { email, password: 'Demo#2026' })
  expect(response.status).toBe(200)
  // REST harness for the detail-only tests. The auth suite exercises the real forms.
  await page.evaluate((token) => {
    const key = 'jungle-marketplace.session'
    const oldValue = sessionStorage.getItem(key)
    sessionStorage.setItem(key, token)
    dispatchEvent(new StorageEvent('storage', { key, oldValue, newValue: token, storageArea: sessionStorage }))
  }, response.data.token)
}
const favorite = (page: Page, mobile: boolean) => page.locator(mobile ? '.favorite-mobile' : '.favorite-detail').getByRole('button').first()
const purchase = (page: Page) => page.getByRole('button', { name: /^(COMPRAR|Comprar NFT)$/ })
const edition = (page: Page, label: string) => page.getByRole('radio', { name: new RegExp(`^Edição ${label},`) })

