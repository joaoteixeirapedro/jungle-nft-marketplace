async function api<T>(page: Page, path: string, method = 'GET', body?: object) {
  return page.evaluate(async ({ path, method, body }) => {
    const token = sessionStorage.getItem('jungle-marketplace.session')
    const guest = sessionStorage.getItem('jungle-marketplace.guest')
    const response = await fetch(`/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(guest ? { 'X-Guest-Id': guest } : {}) }, body: body ? JSON.stringify(body) : undefined })
    return { status: response.status, data: await response.json() as T }
  }, { path, method, body })
}
const scenario = (page: Page, name: string) => api(page, '/__mock/scenario', 'PUT', { scenario: name })
const line = (page: Page, id = 'nft-001:nft-001-ed-50') => page.locator(`[data-line-id="${id}"]`)
const quantity = (page: Page) => line(page).getByRole('spinbutton')
const proceed = (page: Page) => page.getByRole('button', { name: 'Conectar e finalizar', exact: true })
async function accept(page: Page) {
  const button = page.getByRole('button', { name: 'Aceitar valores atualizados' })
  if (await button.isVisible()) { await expect(button).toBeEnabled(); await button.click() }
}
async function quoteReady(page: Page) {
  await expect(page.getByTestId('cart-totals')).toBeVisible()
  await expect(page.getByTestId('cart-totals')).toHaveAttribute('aria-busy', 'false')
  await accept(page)
  await expect(proceed(page)).toBeEnabled()
}
async function add(page: Page, edition = '1/50', qty = '2') {
  await page.goto('/nfts/nft-001')
  await page.getByRole('radio', { name: new RegExp(`^Edição ${edition},`) }).check()
  await page.getByRole('spinbutton', { name: 'Quantidade', exact: true }).fill(qty)
  await page.getByRole('button', { name: /^(COMPRAR|Comprar NFT)$/ }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await quoteReady(page)
}
async function login(page: Page, email: string) {
  await page.goto('/login?redirect=%2Fcart')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill('Demo#2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByTestId('cart-line').first()).toBeVisible()
}
