test('carrinho integra edições, quantidades, remoção, refresh e limites sem duplicar mutations', async ({ page }) => {
  test.setTimeout(45000)
  await add(page)
  await expect(line(page).getByTestId('cart-unit-price')).toContainText('1.19 ETH')
  await expect(line(page).getByTestId('cart-line-total')).toContainText('2.38 ETH')
  await page.reload()
  await quoteReady(page)
  await expect(quantity(page)).toHaveValue('2')
  await add(page, '1/10', '1')
  await expect(page.getByTestId('cart-line')).toHaveCount(2)
  await add(page, '1/50', '1')
  await expect(page.getByTestId('cart-line')).toHaveCount(2)
  await expect(quantity(page)).toHaveValue('3')
  for (const invalid of ['0', '-1', '1.5', '51', '1e2', '']) {
    await quantity(page).fill(invalid)
    await expect(quantity(page)).toHaveAttribute('aria-invalid', 'true')
    await expect(proceed(page)).toBeDisabled()
    await quantity(page).press('Enter')
  }
  await quantity(page).fill('4')
  await quantity(page).press('Enter')
  await expect(quantity(page)).toBeEnabled()
  await quoteReady(page)
  await scenario(page, 'out-of-order')
  await line(page).getByRole('button', { name: /Aumentar quantidade/ }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); button.click() })
  await expect(quantity(page)).toHaveValue('5')
  await quoteReady(page)
  expect((await api<Cart>(page, '/cart')).data.items.find((item) => item.editionId === 'nft-001-ed-50')?.quantity).toBe(5)
  await line(page).getByRole('button', { name: /Diminuir quantidade/ }).click()
  await expect(quantity(page)).toHaveValue('4')
  await quoteReady(page)
  await line(page, 'nft-001:nft-001-ed-10').getByRole('button', { name: /^Remover/ }).click()
  await expect(page.getByTestId('cart-line')).toHaveCount(1)
  await expect(line(page).getByRole('button', { name: /^Remover/ })).toBeFocused()
  await quoteReady(page)
  await line(page).getByRole('button', { name: /^Remover/ }).click()
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Explorar NFTs', exact: true })).toBeFocused()
  await expect(page.getByTestId('cart-totals')).toHaveCount(0)
  expect((await api<Cart>(page, '/cart')).data.items).toEqual([])
})

test('cupons e totais vêm da API com precisão em wei, substituição, expiração e recuperação', async ({ page }) => {
  await add(page)
  await api(page, '/__mock/nfts/nft-001', 'PATCH', { editionId: 'nft-001-ed-50', priceEth: '0.100000000000000001' })
  await expect(line(page).getByTestId('cart-line-total')).toContainText('0.200000000000000002 ETH')
  await quoteReady(page)
  await page.getByLabel('Código promocional', { exact: true }).fill('WELCOME10')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.locator('#coupon-status')).toContainText('Cupom aplicado: WELCOME10')
  await quoteReady(page)
  expect((await api<Cart>(page, '/cart')).data.totals).toEqual({ subtotalEth: '0.200000000000000002', discountEth: '0.02', networkFeeEth: '0.016', totalEth: '0.196000000000000002' })
  await expect(page.getByTestId('cart-total')).toHaveText('0.196000000000000002 ETH')
  for (const code of ['INVALID', 'EXPIRED']) {
    await page.getByLabel('Código promocional', { exact: true }).fill(code)
    await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
    await expect(page.locator('.cart-error').first()).toContainText(code === 'EXPIRED' ? 'expirou' : 'inválido')
    await expect(page.locator('#coupon-status')).toContainText('WELCOME10')
  }
  await scenario(page, 'coupon-expired')
  await page.reload()
  await expect(page.locator('main')).toHaveAttribute('data-realtime-state', 'ready')
  await expect(page.locator('#coupon-status')).toContainText('Cupom expirado')
  await expect(proceed(page)).toBeDisabled()
  await expect(page.locator('.cart-layout')).toHaveAttribute('aria-busy', 'false')
  const removedCoupon = page.waitForResponse((response) => response.request().method() === 'DELETE' && new URL(response.url()).pathname === '/api/cart/coupon' && response.status() === 200)
  await page.getByRole('button', { name: 'Remover cupom', exact: true }).click()
  await removedCoupon
  await quoteReady(page)
  await expect(page.getByTestId('cart-discount')).toHaveText('(-) 0.0 ETH')
  expect((await api<Cart>(page, '/cart')).data.couponCode).toBeNull()
})

test('Socket.IO atualiza preço e estoque, exige revisão e bloqueia esgotamento sem remover itens', async ({ page }) => {
  await add(page)
  const original = await page.getByTestId('cart-totals').getAttribute('data-quote-id')
  await api(page, '/__mock/nfts/nft-001', 'PATCH', { editionId: 'nft-001-ed-50', priceEth: '1.49', availableQuantity: 1 })
  await expect(line(page)).toContainText('1 disponíveis')
  await expect(line(page).getByTestId('cart-unit-price')).toContainText('1.49 ETH')
  await expect(quantity(page)).toHaveValue('2')
  await expect(proceed(page)).toBeDisabled()
  await quantity(page).fill('1')
  await quantity(page).press('Enter')
  await quoteReady(page)
  expect(await page.getByTestId('cart-totals').getAttribute('data-quote-id')).not.toBe(original)
  await api(page, '/__mock/nfts/nft-001', 'PATCH', { editionId: 'nft-001-ed-50', priceEth: '1.79' })
  await expect(page.getByTestId('cart-total')).toHaveText('1.806 ETH')
  await expect(proceed(page)).toBeDisabled()
  await accept(page)
  await expect(proceed(page)).toBeEnabled()
  await scenario(page, 'slow')
  const revalidation = page.waitForRequest((request) => request.method() === 'POST' && new URL(request.url()).pathname === '/api/quotes')
  await proceed(page).click()
  await revalidation
  // The committed update emits through Socket.IO while the quote response is delayed.
  await api(page, '/__mock/nfts/nft-001', 'PATCH', { editionId: 'nft-001-ed-50', priceEth: '1.89' })
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByTestId('cart-total')).toHaveText('1.906 ETH')
  await quoteReady(page)
  await scenario(page, 'default')
  await api(page, '/__mock/nfts/nft-001', 'PATCH', { editionId: 'nft-001-ed-50', availableQuantity: 0 })
  await expect(line(page)).toContainText('Edição esgotada')
  await expect(quantity(page)).toBeDisabled()
  await expect(proceed(page)).toBeDisabled()
  expect((await api<Cart>(page, '/cart')).data.items).toHaveLength(1)
})

test('cotação expira pelo prazo da API e o avanço revalida o snapshot sem criar pedido', async ({ page }) => {
  await page.clock.install()
  await add(page)
  const quote = (await api<Quote>(page, '/quotes', 'POST', {})).data
  await api(page, '/__mock/clock', 'POST', { advanceMs: 300001 })
  await page.clock.fastForward(300001)
  await expect(page.getByText('Cotação expirada. Atualize os valores para continuar.')).toBeVisible()
  await expect(proceed(page)).toBeDisabled()
  await page.getByRole('button', { name: 'Atualizar cotação', exact: true }).click()
  await quoteReady(page)
  const requests: string[] = []
  page.on('request', (request) => { if (/\/api\/(quotes|orders|wallets)/.test(request.url())) requests.push(`${request.method()} ${new URL(request.url()).pathname}`) })
  await proceed(page).click()
  await expect(page).toHaveURL(/\/login\?redirect=%2Fcart$/)
  await expect(page.getByRole('dialog', { name: 'Entrar', exact: true })).toBeVisible()
  await expect(page.locator('.market-shell')).toHaveAttribute('inert', '')
  await expect(page.locator('.cart-page')).toBeVisible()
  await expect(line(page).locator('input[role="spinbutton"]')).toHaveValue('2')
  await page.getByRole('button', { name: 'Voltar sem entrar' }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(quantity(page)).toHaveValue('2')
  expect(requests).toContain('POST /api/quotes')
  expect(requests.some((request) => /orders|wallets/.test(request))).toBe(false)
  expect(quote.totalEth).toBe('2.396')
})

